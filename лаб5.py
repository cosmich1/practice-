## вводим исходную строку с клавиатуры
text = input("Введите строку: ")

## проверяем, не является ли строка пустой
if not text.strip():
    print("Ошибка: введена пустая строка.")
else:
    result = ""
    word = ""

    ## проходим по каждому символу строки для обработки слов и спецсимволов
    for char in text:
        if char.isalnum():
            word += char  # накапливаем буквы и цифры текущего слова
        else:
            result += word[::-1]  # переворачиваем накопленное слово задом наперёд
            word = ""  # очищаем переменную для следующего слова
            result += char  # сохраняем пробел или знак препинания на своём месте

    ## добавляем последнее слово, если строка не заканчивалась спецсимволом
    result += word[::-1]

    ## выводим результат
    print(f"Результат: {result}")
