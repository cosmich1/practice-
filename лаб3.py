## цикл while
n = 0
while n < 1:
    n = int(input("Введите натуральное число N (N >= 1): "))
print(f"Простые числа от 1 до {n}:", end=" ")

## единица не является простым числом, начинаем проверку с 2
for i in range(2, n + 1):

## проверяем делители только до квадратного корня из i
    for j in range(2, int(i ** 0.5) + 1):
        if i % j == 0:
            break  # выходим из цикла, если найден хотя бы один делитель
    else:
        
## else сработает только если цикл завершился без break
        print(i, end=" ")
