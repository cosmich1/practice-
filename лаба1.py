## вариант 10 цилидр
print(str("обьем и периметр цилиндра")) 
## данные
r = float(input("радиус основания R: "))
h = float(input("высота H: "))
pi = 3.14
## формулы
v = pi * r**2 * h
s = 2 * pi * r**2    
## условие для корректного ввода 
if r > 0 or h > 0:     
## вывод
    print(f"объем v:{v:.2f}, площадь поверхности s: {s:.2f}")
else:
    print("введите корректное число")